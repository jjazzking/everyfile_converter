"""데모용 예시 파일 생성.

화면이 빈 상태로 열리면 무엇을 하는 도구인지 알 수 없다. 첫 화면에서 실제 엔진이
돌아간 결과를 보여주기 위해, 실무 파일의 지저분함을 그대로 재현한 표본을 만든다.
바이너리를 리포지토리에 커밋하는 대신 필요할 때 생성한다.
"""

from __future__ import annotations

import io

from openpyxl import Workbook

SAMPLE_NAME = "일반전표_2026Q1_예시.xlsx"

HEADER = ["전표일자", "계정코드", "계정과목", "적요", "거래처", "차변", "대변"]

# 실무에서 마주치는 것들을 일부러 담았다:
# 선행 0 이 있는 계정코드, YYYYMMDD 날짜, 천단위 콤마, 괄호 음수,
# '해당 없음'을 뜻하는 '-', 중간의 소계 행, 빈 셀.
ROWS: list[tuple[str, ...]] = [
    ("20260105", "0110", "현금", "소액현금 보충", "-", "500,000", ""),
    ("20260108", "0251", "외상매입금", "3월분 자재대금", "성일금속(주)", "", "12,400,000"),
    ("20260112", "0813", "복리후생비", "1월 직원 경조사비", "-", "1,200,000", ""),
    ("20260115", "0108", "외상매출금", "1월 매출 청구", "대한물산(주)", "34,500,000", ""),
    ("20260119", "0831", "지급수수료", "세무자문료", "세일회계법인", "3,000,000", ""),
    ("20260122", "0103", "보통예금", "매출대금 입금", "대한물산(주)", "34,500,000", ""),
    ("20260125", "0830", "소모품비", "사무용품 구입 (반품)", "오피스넷", "(240,000)", ""),
    ("20260128", "0134", "선급비용", "화재보험료 선급", "동해화재", "1,800,000", ""),
    ("소계", "", "", "", "", "75,500,000", "12,400,000"),
    ("20260203", "0812", "여비교통비", "부산 출장", "-", "462,300", ""),
    ("20260207", "0146", "상품", "재고 매입", "성일금속(주)", "8,900,000", ""),
    ("20260211", "0108", "외상매출금", "2월 매출 청구", "정우테크", "", ""),
]


def build_workbook() -> Workbook:
    """머리글 2행 + 헤더 3행 + 데이터 구조의 예시 장부."""
    wb = Workbook()
    ws = wb.active
    ws.title = "일반전표"

    ws.append(["2026년 1분기 일반전표"])
    ws.append(["(단위: 원)"])
    ws.append(HEADER)
    for row in ROWS:
        ws.append(list(row))

    # 계정코드 열을 텍스트 서식으로 — 원본에서 선행 0 이 살아있는 상태를 재현한다.
    for r in range(4, 4 + len(ROWS)):
        ws.cell(row=r, column=2).number_format = "@"

    return wb


def sample_bytes() -> bytes:
    buffer = io.BytesIO()
    build_workbook().save(buffer)
    return buffer.getvalue()
